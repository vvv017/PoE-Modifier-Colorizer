    private readonly IReadOnlyDictionary<string, string> _values;

    private UiText(IReadOnlyDictionary<string, string> values) => _values = values;

    public string this[string key] => _values.TryGetValue(key, out string? value) ? value : key;

    public string Status(string status) => _values.TryGetValue("status." + status, out string? value)
        ? value
        : status;

    public static UiText For(string language) => language.Equals("en", StringComparison.OrdinalIgnoreCase)
        ? new UiText(English)
        : new UiText(TraditionalChinese);

